#!/usr/bin/env python3
"""Generate every artifact that restates manifest/rupsha.yaml.

    python3 tools/gen_manifest.py           # write
    python3 tools/gen_manifest.py --check   # exit 1 if anything is stale

Outputs are deterministic (sorted where order carries no meaning, manifest order
where it does), so --check is a byte comparison and CI can run it.
"""

from __future__ import annotations

import argparse
import pathlib
import sys

import yaml

ROOT = pathlib.Path(__file__).resolve().parents[1]
MANIFEST = ROOT / 'manifest' / 'rupsha.yaml'

BANNER = 'GENERATED by tools/gen_manifest.py from manifest/rupsha.yaml -- do not edit.'

ROS_TYPES = {'float32', 'float64', 'int8', 'int32', 'uint8', 'bool', 'string'}


def load() -> dict:
    with open(MANIFEST) as f:
        m = yaml.safe_load(f)
    validate(m)
    return m


def validate(m: dict) -> None:
    fields = m['fields']
    for name, spec in fields.items():
        if spec['type'] not in ROS_TYPES:
            raise SystemExit(f'field {name}: unknown type {spec["type"]}')
    for verb, spec in m['verbs'].items():
        if spec['runs_on'] not in ('board', 'host', 'executive', 'meta'):
            raise SystemExit(f'verb {verb}: bad runs_on {spec["runs_on"]}')
        for f in spec['fields']:
            if f not in fields:
                raise SystemExit(f'verb {verb}: field {f} is not declared under fields:')
        for d in spec.get('defaults', {}):
            if d not in spec['fields']:
                raise SystemExit(f'verb {verb}: default for {d}, which it does not read')
        if spec['runs_on'] == 'host' and 'stream_hz' not in spec:
            raise SystemExit(f'verb {verb}: host verbs must state stream_hz')
    for ename, espec in m['enums'].items():
        for k in espec['values']:
            if not isinstance(k, str) or not k.isidentifier():
                raise SystemExit(f'enum {ename}: key {k!r} is not a name '
                                 f'(YAML 1.1 turns bare OFF/ON/YES/NO into booleans -- quote it)')
    for section in ('state', 'autonomy_status'):
        for name, spec in m[section].items():
            if spec['type'] not in ROS_TYPES:
                raise SystemExit(f'{section}.{name}: unknown type {spec["type"]}')


def _comment(text: str) -> str:
    return f'# {text}' if text else ''


def gen_move_action(m: dict) -> str:
    out = [f'# {BANNER}', '#', '# One verb per goal. `verb` names a row of manifest/rupsha.yaml `verbs:`;',
           '# the typed fields below are read only by the verbs that list them.', '',
           'string verb']
    for name, spec in m['fields'].items():
        unit = f' [{spec["unit"]}]' if spec['unit'] else ''
        default = f' {spec["wire_default"]}' if 'wire_default' in spec else ''
        out.append(f'{spec["type"]:<8} {name + default:<12} {_comment(spec["help"] + unit)}'.rstrip())
    out += ['---',
            'uint8   outcome      # Outcome enum',
            'bool    success      # outcome == SUCCEEDED',
            'string  message',
            'float32 final_value  # verb-specific; NaN when the verb has none',
            'float32 error_value  # verb-specific residual; NaN when none',
            'float32 elapsed_s',
            '---',
            'string  phase',
            'float32 progress     # 0..1, NaN when unknowable',
            'string  status_line',
            '']
    return '\n'.join(out)


def _msg(m: dict, section: str, title: str) -> str:
    out = [f'# {BANNER}', f'# {title}', '', 'std_msgs/Header header']
    for name, spec in m[section].items():
        out.append(f'{spec["type"]:<8} {name:<16} {_comment(spec["help"])}'.rstrip())
    return '\n'.join(out) + '\n'


def gen_py(m: dict) -> str:
    L = [f'"""{BANNER}', '', 'Import attributes, never look keys up by string: a key removed from the',
         'manifest must fail at import, not at the moment a mission needs it.', '"""', '',
         'from enum import IntEnum', '', '']
    for ename, espec in m['enums'].items():
        L.append(f'class {ename}(IntEnum):')
        L.append(f'    """{espec["help"]}"""')
        for k, v in espec['values'].items():
            L.append(f'    {k} = {v}')
        L += ['', '']
    c = m['companion']
    L += ['class Companion:',
          f'    SYSID = {c["sysid"]}',
          f'    COMPID = {c["compid"]}',
          f'    HEARTBEAT_HZ = {c["heartbeat_hz"]!r}', '', '']
    fw = m['firmware']
    L += ['class Firmware:',
          f'    VEHICLE = {fw["vehicle"]!r}',
          f'    MIN_VERSION = {tuple(int(x) for x in fw["min_version"].split("."))!r}',
          f'    GIT = {fw["git"]!r}',
          f'    BOARD_TARGET = {fw["board_target"]!r}', '', '']
    L.append('class Topics:')
    for k, v in m['topics'].items():
        L.append(f'    {k.upper()} = {v!r}')
    L += ['', '']
    L.append('# field -> (ros type, unit)')
    L.append('FIELDS = {')
    for k, v in m['fields'].items():
        L.append(f'    {k!r}: ({v["type"]!r}, {v["unit"]!r}),')
    L += ['}', '']
    L.append('VERBS = {')
    for verb, spec in m['verbs'].items():
        L.append(f'    {verb!r}: {{')
        L.append(f'        "help": {spec["help"]!r},')
        L.append(f'        "runs_on": {spec["runs_on"]!r},')
        L.append(f'        "bypass_busy": {bool(spec.get("bypass_busy", False))!r},')
        if 'stream_hz' in spec:
            L.append(f'        "stream_hz": {spec["stream_hz"]!r},')
        L.append(f'        "fields": {tuple(spec["fields"])!r},')
        L.append(f'        "defaults": {dict(spec.get("defaults", {}))!r},')
        L.append('    },')
    L += ['}', '']
    L.append(f'STATE_FIELDS = {tuple(m["state"].keys())!r}')
    L.append(f'AUTONOMY_STATUS_FIELDS = {tuple(m["autonomy_status"].keys())!r}')
    L.append('')
    return '\n'.join(L)


def gen_reference(m: dict) -> str:
    L = [f'<!-- {BANNER} -->', '', '# Command reference', '',
         'Every verb on `' + m['topics']['move_action'] + '`, generated from `manifest/rupsha.yaml`. ',
         'Where a verb runs is the whole design: **board** = one MAVLink message and the Pixhawk ',
         'closes the loop; **host** = the Pi streams setpoints and checks abort every tick; ',
         '**executive** = the autonomy executive; **meta** = reads and settings.', '',
         f'Companion MAVLink identity: sysid **{m["companion"]["sysid"]}**, compid '
         f'**{m["companion"]["compid"]}**. Firmware floor: **{m["firmware"]["vehicle"]} '
         f'{m["firmware"]["min_version"]}** (`{m["firmware"]["git"]}`, target `{m["firmware"]["board_target"]}`).', '',
         '| verb | runs on | always available | fields (default) | what it does |',
         '|---|---|---|---|---|']
    for verb, spec in m['verbs'].items():
        d = spec.get('defaults', {})
        fs = ', '.join(f'`{f}`' + (f' ({d[f]})' if f in d else '') for f in spec['fields']) or '--'
        rate = f' @ {spec["stream_hz"]} Hz' if 'stream_hz' in spec else ''
        L.append(f'| `{verb}` | {spec["runs_on"]}{rate} | {"yes" if spec.get("bypass_busy") else ""} | {fs} | {spec["help"]} |')
    L += ['', '## Fields', '', '| field | type | unit | meaning |', '|---|---|---|---|']
    for k, v in m['fields'].items():
        L.append(f'| `{k}` | {v["type"]} | {v["unit"]} | {v["help"]} |')
    for ename, espec in m['enums'].items():
        L += ['', f'## `{ename}`', '', espec['help'], '', '| name | value |', '|---|---|']
        for k, v in espec['values'].items():
            L.append(f'| `{k}` | {v} |')
    L += ['', '## `/rupsha/state` (`RupshaState`)', '', 'NaN means absent. It never means zero.', '',
          '| field | type | source |', '|---|---|---|']
    for k, v in m['state'].items():
        L.append(f'| `{k}` | {v["type"]} | {v["help"]} |')
    L += ['', '## Topics', '', '| key | topic |', '|---|---|']
    for k, v in m['topics'].items():
        L.append(f'| `{k}` | `{v}` |')
    L.append('')
    return '\n'.join(L)


def outputs(m: dict) -> dict[pathlib.Path, str]:
    return {
        ROOT / 'src/rupsha_interfaces/action/Move.action': gen_move_action(m),
        ROOT / 'src/rupsha_interfaces/msg/RupshaState.msg': _msg(m, 'state', 'Vehicle snapshot on /rupsha/state. NaN = absent.'),
        ROOT / 'src/rupsha_interfaces/msg/AutonomyStatus.msg': _msg(m, 'autonomy_status', 'Executive status on /rupsha/autonomy_status.'),
        ROOT / 'src/rupsha_control/rupsha_control/manifest.py': gen_py(m),
        ROOT / '.claude/context/reference/commands.md': gen_reference(m),
    }


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument('--check', action='store_true', help='fail if any output is stale')
    args = ap.parse_args()
    m = load()
    stale = []
    for path, text in outputs(m).items():
        current = path.read_text() if path.exists() else None
        if current == text:
            continue
        if args.check:
            stale.append(path.relative_to(ROOT))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
            print(f'wrote {path.relative_to(ROOT)}')
    if stale:
        print('stale (run python3 tools/gen_manifest.py):', *stale, sep='\n  ')
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main())
