"""Seeded worlds: seed -> scenario (YAML) -> SDF.

    python3 -m rupsha_sim.worldgen            # regenerate every committed world
    python3 -m rupsha_sim.worldgen --check    # exit 1 if any is stale

A scenario is the ground truth a scorer reads (where every post, object and rock
is, in metres east/north of the world origin = SITL home), so a test asks "did
the rover stop within 2 m of post 3" against the file that built the world, not
against what the rover believed. Same seed, same world, byte for byte.

Posts follow URC: ArUco DICT_4X4_50, 20 cm black square, on all four faces of a
cube on a pole. The texture is generated by cv2.aruco, so the dictionary in the
world and in the detector cannot disagree.
"""

from __future__ import annotations

import argparse
import math
import pathlib
import random
import sys

import yaml

from . import model_gen
from .sitl import DEFAULT_HOME

PKG = pathlib.Path(__file__).resolve().parent.parent
MARKER_M = 0.20
MARKER_PX = 400
QUIET_PX = 60                      # white border around the black square
POST_TOP_M = 0.75

OBJECT_SHAPES = {
    # Primitive stand-ins. A detector trained on real photos will not fire on
    # these; they exist for geometry, routing and ground-truth scoring. Meshes
    # are on the roadmap.
    'mallet': ('box', (0.30, 0.08, 0.08), '0.8 0.4 0.1 1'),
    'bottle': ('cylinder', (0.035, 0.22), '0.2 0.5 0.9 1'),
    'hammer': ('box', (0.28, 0.05, 0.05), '0.5 0.5 0.5 1'),
}

WORLDS = {
    'flat_ci': {'seed': 7, 'size_m': 40.0, 'posts': 3, 'objects': 0, 'rocks': 0},
    'playpen': {'seed': 11, 'size_m': 60.0, 'posts': 4, 'objects': 2, 'rocks': 12},
}


def scenario(name: str, seed: int, size_m: float, posts: int, objects: int, rocks: int,
             home=DEFAULT_HOME) -> dict:
    rng = random.Random(seed)
    half = size_m / 2
    placed = [(0.0, 0.0, 3.0)]           # keep the spawn clear

    def free_spot(clearance):
        for _ in range(1000):
            e, n = rng.uniform(-half + 2, half - 2), rng.uniform(-half + 2, half - 2)
            if all(math.hypot(e - pe, n - pn) > clearance + pr for pe, pn, pr in placed):
                return round(e, 2), round(n, 2)
        raise RuntimeError(f'{name}: cannot place everything in {size_m} m')

    out_posts, out_objects, out_rocks = [], [], []
    for i in range(posts):
        e, n = free_spot(6.0)
        placed.append((e, n, 1.0))
        out_posts.append({'tag_id': i + 1, 'east': e, 'north': n})
    names = sorted(OBJECT_SHAPES)
    for i in range(objects):
        e, n = free_spot(5.0)
        placed.append((e, n, 1.0))
        out_objects.append({'class': names[i % len(names)], 'east': e, 'north': n,
                            'yaw': round(rng.uniform(0, 2 * math.pi), 3)})
    for _ in range(rocks):
        r = round(rng.uniform(0.25, 0.7), 2)
        e, n = free_spot(2.5)
        placed.append((e, n, r))
        out_rocks.append({'east': e, 'north': n, 'radius': r})
    return {'name': name, 'seed': seed, 'size_m': size_m,
            'home': {'lat': home[0], 'lon': home[1], 'alt': home[2], 'heading': home[3]},
            'posts': out_posts, 'objects': out_objects, 'rocks': out_rocks}


def marker_pixels(tag_id: int):
    """The marker as a uint8 array. OpenCV 4.7 renamed drawMarker to
    generateImageMarker; the bit patterns are the same, so both give one image."""
    import cv2
    import numpy as np
    d = cv2.aruco.getPredefinedDictionary(cv2.aruco.DICT_4X4_50)
    if hasattr(cv2.aruco, 'generateImageMarker'):
        inner = cv2.aruco.generateImageMarker(d, tag_id, MARKER_PX)
    else:
        inner = cv2.aruco.drawMarker(d, tag_id, MARKER_PX)
    img = np.full((MARKER_PX + 2 * QUIET_PX,) * 2, 255, np.uint8)
    img[QUIET_PX:QUIET_PX + MARKER_PX, QUIET_PX:QUIET_PX + MARKER_PX] = inner
    return img


def _png_gray8(img) -> bytes:
    """Minimal 8-bit greyscale PNG writer: same bytes on every OpenCV build."""
    import struct
    import zlib
    h, w = img.shape

    def chunk(tag, data):
        return struct.pack('>I', len(data)) + tag + data + struct.pack('>I', zlib.crc32(tag + data))
    raw = b''.join(b'\x00' + img[r].tobytes() for r in range(h))
    return (b'\x89PNG\r\n\x1a\n' + chunk(b'IHDR', struct.pack('>IIBBBBB', w, h, 8, 0, 0, 0, 0))
            + chunk(b'IDAT', zlib.compress(raw, 9)) + chunk(b'IEND', b''))


def marker_png(tag_id: int) -> bytes:
    return _png_gray8(marker_pixels(tag_id))


def same_content(path: pathlib.Path, content) -> bool:
    """Generated output already on disk? PNGs compare by pixels, not bytes."""
    if not path.exists():
        return False
    if isinstance(content, str):
        return path.read_text() == content
    if path.suffix == '.png':
        import cv2
        import numpy as np
        a = cv2.imdecode(np.frombuffer(path.read_bytes(), np.uint8), cv2.IMREAD_UNCHANGED)
        b = cv2.imdecode(np.frombuffer(content, np.uint8), cv2.IMREAD_UNCHANGED)
        return a is not None and b is not None and a.shape == b.shape and bool((a == b).all())
    return path.read_bytes() == content


def post_model(tag_id: int) -> tuple[str, str]:
    cube = MARKER_M * (MARKER_PX + 2 * QUIET_PX) / MARKER_PX
    name = f'aruco_post_{tag_id}'
    sdf = f"""<?xml version="1.0"?>
<!-- GENERATED by rupsha_sim.worldgen -- do not edit. -->
<sdf version="1.9">
  <model name="{name}">
    <static>true</static>
    <link name="link">
      <collision name="pole"><pose>0 0 {POST_TOP_M / 2} 0 0 0</pose>
        <geometry><cylinder><radius>0.04</radius><length>{POST_TOP_M}</length></cylinder></geometry></collision>
      <visual name="pole"><pose>0 0 {POST_TOP_M / 2} 0 0 0</pose>
        <geometry><cylinder><radius>0.04</radius><length>{POST_TOP_M}</length></cylinder></geometry>
        <material><ambient>0.9 0.6 0.1 1</ambient><diffuse>0.9 0.6 0.1 1</diffuse></material></visual>
      <collision name="tag"><pose>0 0 {POST_TOP_M + cube / 2} 0 0 0</pose>
        <geometry><box><size>{cube:.4f} {cube:.4f} {cube:.4f}</size></box></geometry></collision>
      <visual name="tag"><pose>0 0 {POST_TOP_M + cube / 2} 0 0 0</pose>
        <geometry><box><size>{cube:.4f} {cube:.4f} {cube:.4f}</size></box></geometry>
        <material><diffuse>1 1 1 1</diffuse><ambient>1 1 1 1</ambient>
          <pbr><metal><albedo_map>model://{name}/materials/textures/marker_{tag_id}.png</albedo_map>
            <roughness>1.0</roughness><metalness>0.0</metalness></metal></pbr></material></visual>
    </link>
  </model>
</sdf>
"""
    cfg = (f'<?xml version="1.0"?>\n<model><name>{name}</name><version>0.1</version>'
           f'<sdf version="1.9">model.sdf</sdf><description>URC-style ArUco 4x4_50 id {tag_id}, '
           f'{MARKER_M * 100:.0f} cm (generated)</description></model>\n')
    return sdf, cfg


def _object_sdf(i, o):
    kind, dims, rgba = OBJECT_SHAPES[o['class']]
    geom = (f'<box><size>{dims[0]} {dims[1]} {dims[2]}</size></box>' if kind == 'box'
            else f'<cylinder><radius>{dims[0]}</radius><length>{dims[1]}</length></cylinder>')
    z = dims[2] / 2 if kind == 'box' else dims[1] / 2
    return f"""
    <model name="object_{i}_{o['class']}"><static>true</static>
      <pose>{o['east']} {o['north']} {z} 0 0 {o['yaw']}</pose>
      <link name="link"><collision name="c"><geometry>{geom}</geometry></collision>
        <visual name="v"><geometry>{geom}</geometry><material><ambient>{rgba}</ambient><diffuse>{rgba}</diffuse></material></visual></link>
    </model>"""


def world_sdf(sc: dict) -> str:
    h = sc['home']
    parts = [f"""<?xml version="1.0"?>
<!-- GENERATED by rupsha_sim.worldgen from scenarios/{sc['name']}.yaml (seed {sc['seed']}) -- do not edit. -->
<sdf version="1.9">
  <world name="{sc['name']}">
    <physics name="1ms" type="ignore"><max_step_size>0.001</max_step_size><real_time_factor>1.0</real_time_factor></physics>
    <plugin filename="gz-sim-physics-system" name="gz::sim::systems::Physics"/>
    <plugin filename="gz-sim-user-commands-system" name="gz::sim::systems::UserCommands"/>
    <plugin filename="gz-sim-scene-broadcaster-system" name="gz::sim::systems::SceneBroadcaster"/>
    <plugin filename="gz-sim-sensors-system" name="gz::sim::systems::Sensors"><render_engine>ogre2</render_engine></plugin>
    <plugin filename="gz-sim-imu-system" name="gz::sim::systems::Imu"/>
    <spherical_coordinates>
      <surface_model>EARTH_WGS84</surface_model><world_frame_orientation>ENU</world_frame_orientation>
      <latitude_deg>{h['lat']}</latitude_deg><longitude_deg>{h['lon']}</longitude_deg>
      <elevation>{h['alt']}</elevation><heading_deg>0</heading_deg>
    </spherical_coordinates>
    <scene><ambient>0.6 0.6 0.6 1</ambient><background>0.7 0.8 0.95 1</background><shadows>true</shadows></scene>
    <light type="directional" name="sun"><cast_shadows>true</cast_shadows><pose>0 0 30 0 0 0</pose>
      <diffuse>0.9 0.9 0.85 1</diffuse><specular>0.2 0.2 0.2 1</specular><direction>-0.4 0.3 -0.9</direction></light>
    <model name="ground"><static>true</static><link name="link">
      <collision name="c"><geometry><plane><normal>0 0 1</normal><size>{sc['size_m'] * 2} {sc['size_m'] * 2}</size></plane></geometry>
        <surface><friction><ode><mu>1.0</mu><mu2>1.0</mu2></ode></friction></surface></collision>
      <visual name="v"><geometry><plane><normal>0 0 1</normal><size>{sc['size_m'] * 2} {sc['size_m'] * 2}</size></plane></geometry>
        <material><ambient>0.55 0.45 0.35 1</ambient><diffuse>0.55 0.45 0.35 1</diffuse></material></visual></link></model>
    <include><uri>model://{model_gen.NAME}</uri><name>rupsha</name><pose>0 0 0.02 0 0 {math.radians(90 - h['heading']):.5f}</pose></include>"""]
    for p in sc['posts']:
        parts.append(f"""
    <include><uri>model://aruco_post_{p['tag_id']}</uri><name>post_{p['tag_id']}</name><pose>{p['east']} {p['north']} 0 0 0 0</pose></include>""")
    for i, o in enumerate(sc['objects']):
        parts.append(_object_sdf(i, o))
    for i, r in enumerate(sc['rocks']):
        parts.append(f"""
    <model name="rock_{i}"><static>true</static><pose>{r['east']} {r['north']} {r['radius'] * 0.4} 0 0 0</pose>
      <link name="link"><collision name="c"><geometry><sphere><radius>{r['radius']}</radius></sphere></geometry></collision>
        <visual name="v"><geometry><sphere><radius>{r['radius']}</radius></sphere></geometry>
          <material><ambient>0.4 0.38 0.35 1</ambient><diffuse>0.4 0.38 0.35 1</diffuse></material></visual></link></model>""")
    parts.append('\n  </world>\n</sdf>\n')
    return ''.join(parts)


def outputs() -> dict:
    """Every generated file: path -> str | bytes."""
    from . import ackermann_gen
    out = dict(model_gen.outputs())
    out.update(ackermann_gen.outputs())
    tags = set()
    for name, spec in WORLDS.items():
        sc = scenario(name, **spec)
        out[PKG / 'scenarios' / f'{name}.yaml'] = (
            f'# GENERATED by rupsha_sim.worldgen (seed {spec["seed"]}) -- ground truth for scorers.\n'
            + yaml.safe_dump(sc, sort_keys=False))
        out[PKG / 'worlds' / f'{name}.sdf'] = world_sdf(sc)
        tags |= {p['tag_id'] for p in sc['posts']}
    for t in sorted(tags):
        d = PKG / 'models' / f'aruco_post_{t}'
        sdf, cfg = post_model(t)
        out[d / 'model.sdf'] = sdf
        out[d / 'model.config'] = cfg
        out[d / 'materials' / 'textures' / f'marker_{t}.png'] = marker_png(t)
    out[PKG / 'config' / 'bridge.yaml'] = __import__('rupsha_sim.contract', fromlist=['x']).bridge_yaml()
    return out


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument('--check', action='store_true')
    args = ap.parse_args(argv)
    stale = []
    for path, content in outputs().items():
        if same_content(path, content):
            continue
        if args.check:
            stale.append(path.relative_to(PKG))
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        with open(path, 'wb' if isinstance(content, bytes) else 'w') as f:
            f.write(content)
        print(f'wrote {path.relative_to(PKG)}')
    if stale:
        print('stale (run python3 -m rupsha_sim.worldgen):', *stale, sep='\n  ')
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main())
