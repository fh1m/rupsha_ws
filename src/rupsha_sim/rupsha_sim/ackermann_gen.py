def outputs() -> dict:
    return {
        PKG / 'models' / NAME / 'model.urdf': model_urdf(),
        PKG / 'worlds' / 'ackermann_ci.sdf': world_sdf(),
        PKG / 'config' / 'ackermann_bridge.yaml': contract.ackermann_bridge_yaml(),
        PKG / 'config' / 'ackermann_controllers.yaml': controllers_yaml(),
    }
