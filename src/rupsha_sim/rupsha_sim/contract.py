"""The sim contract: what any simulator backend must provide to the stack.

The stack never knows it is in a simulator. A backend (Gazebo Harmonic today,
Jetty / Isaac later) earns the right to be used by producing exactly these
topics, on these types, in these frames -- and nothing in rupsha_control,
_vision, _localization or _planner may subscribe to a backend-specific name.

    /clock                           rosgraph_msgs/Clock       sim time
    Topics.CAMERA_FRONT              sensor_msgs/Image         what the Pi's camera would publish
    Topics.CAMERA_FRONT_INFO         sensor_msgs/CameraInfo    calibrated by construction (exact pinhole)
    /sim/ground_truth/odometry       nav_msgs/Odometry         world-frame truth, for scorers ONLY

The previous body spoke MAVLink on tcp:127.0.0.1:5760. The Ackermann body
speaks /rupsha/board/command and /rupsha/board/state. Truth is still
/sim/ground_truth/odometry, for scorers only.

`bridge_table()` generates the ros_gz_bridge config, and
test_sim_contract_drift checks it, the model SDF and the manifest agree.
"""

from __future__ import annotations

from rupsha_control.manifest import Topics

MODEL = 'rupsha'
GZ_CAMERA_FRONT = 'sim/camera/front/image'
GZ_CAMERA_FRONT_INFO = 'sim/camera/front/camera_info'
GZ_ODOMETRY = f'model/{MODEL}/odometry'
GROUND_TRUTH_ODOMETRY = '/sim/ground_truth/odometry'
GZ_IMU = 'sim/imu'
GZ_NAVSAT = 'sim/navsat'
SIM_IMU = '/rupsha/sim/imu'
SIM_NAVSAT = '/rupsha/sim/navsat'
SITL_URL = 'tcp:127.0.0.1:5760'
CONTROLLERS_TOKEN = '__RUPSHA_CONTROLLERS__'

# Exact pinhole of the simulated camera. The Pi camera's real calibration
# replaces this; the vision node reads camera_info, never these numbers.
CAMERA_WIDTH = 640
CAMERA_HEIGHT = 480
CAMERA_HFOV_RAD = 1.2217304763960306        # 70 deg
CAMERA_RATE_HZ = 15


def bridge_table() -> list[dict]:
    """ros_gz_bridge parameter_bridge entries, GZ_TO_ROS only: the sim never takes commands over ROS."""
    rows = [
        ('/clock', 'clock', 'rosgraph_msgs/msg/Clock', 'gz.msgs.Clock'),
        (Topics.CAMERA_FRONT, GZ_CAMERA_FRONT, 'sensor_msgs/msg/Image', 'gz.msgs.Image'),
        (Topics.CAMERA_FRONT_INFO, GZ_CAMERA_FRONT_INFO, 'sensor_msgs/msg/CameraInfo',
         'gz.msgs.CameraInfo'),
        (GROUND_TRUTH_ODOMETRY, GZ_ODOMETRY, 'nav_msgs/msg/Odometry', 'gz.msgs.Odometry'),
    ]
    return [{'ros_topic_name': r, 'gz_topic_name': g, 'ros_type_name': rt, 'gz_type_name': gt,
             'direction': 'GZ_TO_ROS'} for r, g, rt, gt in rows]


def bridge_yaml() -> str:
    import yaml
    head = '# GENERATED by rupsha_sim.contract.bridge_yaml() -- do not edit.\n'
    return head + yaml.safe_dump(bridge_table(), sort_keys=False)


def ackermann_bridge_table() -> list[dict]:
    """The skid bridge, plus the IMU and the navsat the board contract reads.

    Still GZ_TO_ROS only. Speed and steer go through ros2_control, not this bridge.
    """
    extra = [
        (SIM_IMU, GZ_IMU, 'sensor_msgs/msg/Imu', 'gz.msgs.IMU'),
        (SIM_NAVSAT, GZ_NAVSAT, 'sensor_msgs/msg/NavSatFix', 'gz.msgs.NavSat'),
    ]
    rows = bridge_table()
    rows += [{'ros_topic_name': r, 'gz_topic_name': g, 'ros_type_name': rt, 'gz_type_name': gt,
              'direction': 'GZ_TO_ROS'} for r, g, rt, gt in extra]
    return rows


def ackermann_bridge_yaml() -> str:
    import yaml
    head = '# GENERATED by rupsha_sim.contract.ackermann_bridge_yaml() -- do not edit.\n'
    return head + yaml.safe_dump(ackermann_bridge_table(), sort_keys=False)
